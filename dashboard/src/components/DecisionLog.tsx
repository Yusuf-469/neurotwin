"use client";

import { useState } from "react";
import { api, type DecisionRecord, type Explanation } from "@/lib/api";

interface Props {
  sessionId: string;
  decisions: DecisionRecord[];
  total: number;
}

export default function DecisionLog({ sessionId, decisions, total }: Props) {
  const [explanation, setExplanation] = useState<Explanation | null>(null);
  const [error, setError] = useState<string>("");

  const explain = async (id: number) => {
    setError("");
    try {
      setExplanation((await api.explanation(sessionId, id)).explanation);
    } catch (e) {
      setError(String(e));
    }
  };

  return (
    <div className="panel">
      <h2>Recent decisions ({total} total)</h2>
      <div className="scroll">
        <table>
          <thead>
            <tr>
              <th>#</th><th>time (h)</th><th>action</th><th>request</th><th>priority</th>
              <th>waited (h)</th><th>unit</th><th></th>
            </tr>
          </thead>
          <tbody>
            {[...decisions].reverse().map((d) => (
              <tr key={d.decision_id}>
                <td>{d.decision_id}</td>
                <td>{d.time.toFixed(1)}</td>
                <td>{d.action}</td>
                <td>{d.request_type?.replace("_", " ") ?? "—"}</td>
                <td>{d.priority ?? "—"}</td>
                <td>{d.waited_hours?.toFixed(1) ?? "—"}</td>
                <td className={d.off_service ? "bad" : ""}>
                  {d.unit ?? "—"}{d.off_service ? " (off-service)" : ""}
                </td>
                <td><button className="secondary" onClick={() => explain(d.decision_id)}>explain</button></td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {error && <p className="error">{error}</p>}
      {explanation && (
        <div className="panel" style={{ marginTop: 12 }}>
          <h2>Decision #{explanation.decision_id}</h2>
          <p><strong>{explanation.summary}</strong></p>
          <p>{explanation.reasoning}</p>
          <p className="muted">Facts used: {explanation.facts_used.join("; ")}</p>
          <p className="muted">
            Reliability indicator (grounding, not a statistical confidence): {explanation.reliability_indicator}.
            Generated by: {explanation.generated_by}.
          </p>
          <p className="muted">{explanation.limitations}</p>
        </div>
      )}
    </div>
  );
}
