"""Non-homogeneous Poisson arrivals (RESEARCH.md v2 §6.6).

The rate is piecewise constant on 1-hour bins over a 168-hour week (time 0 = Monday 00:00).
Arrivals are generated by thinning (Lewis & Shedler): candidate points from a homogeneous
process at the maximum rate are accepted with probability lambda(t) / lambda_max. Thinning is
exact for any bounded rate function.
"""

from __future__ import annotations

import math

import numpy as np

from .config import ScenarioConfig, SimulationConfig

HOURS_PER_WEEK = 168


class PiecewiseConstantRate:
    """lambda(t) taking a constant value on each hour of the week, repeating weekly."""

    def __init__(self, weekly_rates: np.ndarray) -> None:
        rates = np.asarray(weekly_rates, dtype=float)
        if rates.shape != (HOURS_PER_WEEK,) or np.any(rates < 0):
            raise ValueError("need 168 non-negative hourly rates")
        self.rates = rates
        self.max_rate = float(rates.max())

    def rate(self, t: float) -> float:
        return float(self.rates[int(t) % HOURS_PER_WEEK])

    def integral(self, a: float, b: float) -> float:
        """Exact integral of lambda over [a, b] (used by tests and validation)."""
        if b < a:
            raise ValueError("need a <= b")
        total, t = 0.0, a
        while t < b:
            bin_end = min(math.floor(t) + 1.0, b)
            total += self.rate(t) * (bin_end - t)
            t = bin_end
        return total


class ThinningArrivalProcess:
    """Generates successive arrival times from one dedicated RNG stream."""

    def __init__(self, rate: PiecewiseConstantRate, rng: np.random.Generator) -> None:
        self._rate = rate
        self._rng = rng

    def next_arrival(self, t: float) -> float:
        """First arrival strictly after time t (infinity if the rate is identically zero)."""
        lam_max = self._rate.max_rate
        if lam_max <= 0:
            return math.inf
        while True:
            t += self._rng.exponential(1.0 / lam_max)
            if self._rng.random() * lam_max < self._rate.rate(t):
                return t


def emergency_rate(config: SimulationConfig, scenario: ScenarioConfig) -> PiecewiseConstantRate:
    """lambda_E(t) = base_E * arrival_multiplier * f_hour(t) * f_day(t)."""
    hours = np.arange(HOURS_PER_WEEK)
    hourly = np.asarray(config.hourly_profile)[hours % 24]
    daily = np.asarray(config.weekly_profile)[hours // 24]
    return PiecewiseConstantRate(
        config.emergency_base_rate * scenario.arrival_multiplier * hourly * daily
    )


def elective_rate(config: SimulationConfig, scenario: ScenarioConfig) -> PiecewiseConstantRate:
    """Electives arrive only in the elective window; scaled so base_L is the weekly mean rate."""
    hours = np.arange(HOURS_PER_WEEK)
    start, end = config.elective_hours
    open_mask = (
        np.isin(hours // 24, config.elective_weekdays) & (hours % 24 >= start) & (hours % 24 < end)
    )
    n_open = int(open_mask.sum())
    rates = np.zeros(HOURS_PER_WEEK)
    if n_open and config.elective_base_rate > 0:
        rates[open_mask] = (
            config.elective_base_rate * scenario.arrival_multiplier * HOURS_PER_WEEK / n_open
        )
    return PiecewiseConstantRate(rates)
